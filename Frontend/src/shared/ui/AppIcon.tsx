export type AppIconName = keyof typeof AppIconCatalog;

export function isAppIconName(value: unknown): value is AppIconName {
  return typeof value === "string" && Object.prototype.hasOwnProperty.call(AppIconCatalog, value);
}

export function AppIcon({
  icon,
  size = 16,
  strokeWidth = 1.75,
  className,
  ...props
}: Omit<SVGProps<SVGSVGElement>, "height" | "width" | "strokeWidth"> & {
  icon: AppIconName;
  size?: number | string;
  strokeWidth?: number;
}): JSX.Element {
  const Icon = AppIconCatalog[icon];
  const ariaHidden = props["aria-hidden"] ?? (props["aria-label"] || props["aria-labelledby"] ? undefined : true);

  return (
    <Icon
      {...props}
      aria-hidden={ariaHidden}
      width={size}
      height={size}
      strokeWidth={strokeWidth}
      className={cn("shrink-0", className)}
    />
  );
}
