/**
 * `activity` is an identity glyph, not a live-state switch. Live wrappers
 * animate its paths from their own status, while standalone uses stay still.
 */
function StaticSeneraActivityMark(props: ComponentProps<typeof SeneraActivityMark>): JSX.Element {
  return <SeneraActivityMark {...props} active={false} />;
}

