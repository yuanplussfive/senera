import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { format } from "prettier";
import { isMainModule } from "../Source/AgentSystem/Core/AgentPath.js";

// The optional client ships its exact host contract as source, with no runtime
// dependency on files outside its npm workspace or a parallel hand-written DTO.
export async function generateAgentDirectoryClientContract(root: string, check = false): Promise<void> {
  const preset = await readFile(path.join(root, "Source/AgentSystem/Core/AgentPromptPresetContract.ts"), "utf8");
  const directory = await readFile(path.join(root, "Source/AgentSystem/Core/AgentDirectoryContract.ts"), "utf8");
  const profile = await readFile(path.join(root, "Source/AgentSystem/Core/AgentProfileContract.ts"), "utf8");
  const resources = await readFile(path.join(root, "Source/AgentSystem/Resources/AgentResourceContract.ts"), "utf8");
  const identities = await readFile(path.join(root, "Source/AgentSystem/Identity/AgentShortId.ts"), "utf8");
  const content = await format(
    `// Generated by Build/GenerateAgentDirectoryClientContract.ts. Do not edit.\n${identities}\n${preset}\n${directory.replace(/^import \{ (?:normalizeAgentPromptPresetPath|AgentShortIdPattern) \} from .*;\r?\n/gmu, "")}\n${profile.replace(/^import \{ z \} from "zod";\r?\n/mu, "")}\n${resources}`,
    { parser: "typescript", printWidth: 120 },
  );
  const target = path.join(root, "Frontend/qq/client/src/renderer/src/runtime/agentDirectoryContract.generated.ts");
  if (check) {
    if ((await readFile(target, "utf8")) !== content)
      throw new Error("QQ client Agent contract is out of date. Run npm run generate.agent-directory-client.");
  } else await writeFile(target, content);
  const logo = await readFile(path.join(root, "Frontend/public/favicon.svg"), "utf8");
  const logoTarget = path.join(root, "Frontend/qq/client/src/renderer/src/assets/senera.generated.svg");
  if (check) {
    if ((await readFile(logoTarget, "utf8")) !== logo)
      throw new Error("QQ client brand asset is out of date. Run npm run generate.agent-directory-client.");
  } else await writeFile(logoTarget, logo);
}
if (isMainModule(import.meta.url))
  await generateAgentDirectoryClientContract(process.cwd(), process.argv.includes("--check"));
