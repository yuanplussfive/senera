import path from "node:path";
import { format, resolveConfig } from "prettier";
import {
  assertAgentSelfCommandContract,
  projectAgentSelfCommandContract,
} from "../Source/AgentSystem/SelfService/AgentSelfCommandContract.js";
import { renderAgentSelfCliHelp } from "../Source/AgentSystem/SelfService/AgentSelfCommandRegistry.js";
import { synchronizeGeneratedFile } from "./GeneratedTextFile.js";

const filePath = path.resolve("System/Skills/senera-workbench/references/cli-reference.md");
const check = process.argv.includes("--check");
assertAgentSelfCommandContract();
const contract = projectAgentSelfCommandContract();
const source = [
  "# Command index",
  "",
  "<!-- Generated by npm run generate.self-command-contract. -->",
  "",
  `Command contract v${contract.version}, revision: \`${contract.revision}\`.`,
  "",
  "Use `senera capabilities DOMAIN [ACTION] --json` for the running host's exact",
  "arguments, JSON input schema and plugin commands. Use `senera DOMAIN --help`",
  "for built-in usage. The registry and Zod schema are checked together; this",
  "index does not define a second command contract.",
  "",
  "```text",
  renderAgentSelfCliHelp(),
  "```",
  "",
].join("\n");
const content = await format(source, { ...(await resolveConfig(filePath)), filepath: filePath });
synchronizeGeneratedFile({ filePath, content, check, regenerateCommand: "npm run generate.self-command-contract" });
console.log(`Self-service CLI contract ${check ? "verified" : "generated"}.`);
